import numpy as np
import random

crops = ["Wheat", "Maize", "Cotton"]
num_crops = len(crops)
num_stages = 3

TOTAL_LAND = 100.0
SEASONAL_WATER_SUPPLY = [150000.0, 220000.0, 120000.0]
WATER_COST = 0.05

price_per_ton = [250.0, 200.0, 750.0]
max_yield = [5.0, 8.0, 3.0]
cultivation_cost = [400.0, 500.0, 650.0]

w_max = [
    [1000.0, 2000.0, 1000.0],
    [1200.0, 2800.0, 1500.0],
    [1500.0, 3500.0, 2000.0]
]

ky = [
    [0.2, 0.6, 0.2],
    [0.4, 1.2, 0.5],
    [0.3, 0.8, 0.4]
]

land_options = [0.0, 10.0, 20.0, 30.0, 40.0, 50.0, 60.0]
water_ratios = [0.6, 0.8, 1.0]

choices = [(l, r) for l in land_options for r in water_ratios if not (l == 0 and r != 1.0)]
num_choices = len(choices)

def calculate_profit(solution):
    total_profit = 0.0
    for i, (area, ratio) in enumerate(solution):
        if area == 0:
            continue

        yield_factor = 1.0
        total_water_used = 0.0
        for t in range(num_stages):
            w_applied = w_max[i][t] * ratio
            total_water_used += w_applied * area
            stress = 1.0 - ky[i][t] * (1.0 - ratio)
            yield_factor *= max(0.0, stress)

        actual_yield = max_yield[i] * yield_factor
        revenue = price_per_ton[i] * actual_yield * area
        cost = (cultivation_cost[i] * area) + (WATER_COST * total_water_used)
        total_profit += (revenue - cost)

    return total_profit

NUM_ANTS = 30
MAX_ITER = 100
ALPHA = 1.0
BETA = 2.0
RHO = 0.15
Q = 100.0

tau = np.ones((num_crops, num_choices))

eta = np.ones((num_crops, num_choices))
for i in range(num_crops):
    for c_idx, (area, ratio) in enumerate(choices):
        if area > 0:
            est_profit = calculate_profit([(area, ratio) if idx == i else (0, 1.0) for idx in range(num_crops)])
            eta[i][c_idx] = max(1.0, est_profit / (area + 1))

best_solution = None
best_profit = -float("inf")

for iteration in range(MAX_ITER):
    ant_solutions = []

    for ant in range(NUM_ANTS):
        current_sol = [None] * num_crops
        rem_land = TOTAL_LAND
        rem_water = list(SEASONAL_WATER_SUPPLY)

        crop_order = list(range(num_crops))
        random.shuffle(crop_order)

        for i in crop_order:
            valid_indices = []
            for c_idx, (area, ratio) in enumerate(choices):
                if area <= rem_land:
                    water_needed = [w_max[i][t] * ratio * area for t in range(num_stages)]
                    if all(water_needed[t] <= rem_water[t] for t in range(num_stages)):
                        valid_indices.append(c_idx)

            if not valid_indices:
                chosen_idx = 0
            else:
                probs = []
                for c_idx in valid_indices:
                    val = (tau[i][c_idx] ** ALPHA) * (eta[i][c_idx] ** BETA)
                    probs.append(val)

                prob_sum = sum(probs)
                probs = [p / prob_sum for p in probs]
                chosen_idx = np.random.choice(valid_indices, p=probs)

            area, ratio = choices[chosen_idx]
            current_sol[i] = (area, ratio, chosen_idx)

            rem_land -= area
            for t in range(num_stages):
                rem_water[t] -= (w_max[i][t] * ratio * area)

        clean_sol = [(x[0], x[1]) for x in current_sol]
        profit = calculate_profit(clean_sol)
        ant_solutions.append((current_sol, profit))

        if profit > best_profit:
            best_profit = profit
            best_solution = current_sol

    tau *= (1.0 - RHO)

    for sol, profit in ant_solutions:
        if profit > 0:
            delta_tau = Q * (profit / best_profit)
            for i, (_, _, c_idx) in enumerate(sol):
                tau[i][c_idx] += delta_tau

print(f"Optimal Total Net Profit: ${best_profit:,.2f}\n")
print(f"{'Crop':<10} | {'Area (ha)':<10} | {'Water Level':<12} | {'Stage 1 (m3)':<12} | {'Stage 2 (m3)':<12} | {'Stage 3 (m3)':<12}")
print("-" * 80)

total_area_used = 0
total_water_stage = [0.0] * num_stages

for i, (area, ratio, _) in enumerate(best_solution):
    total_area_used += area
    w_stages = [w_max[i][t] * ratio * area for t in range(num_stages)]
    for t in range(num_stages):
        total_water_stage[t] += w_stages[t]

    print(f"{crops[i]:<10} | {area:<10.1f} | {int(ratio*100):>10}% | {w_stages[0]:<12,.0f} | {w_stages[1]:<12,.0f} | {w_stages[2]:<12,.0f}")

print("-" * 80)
print(f"Total Land Used: {total_area_used:.1f} / {TOTAL_LAND} ha")
print(f"Total Water Used per Stage: {[round(w) for w in total_water_stage]} / {SEASONAL_WATER_SUPPLY} m3")

